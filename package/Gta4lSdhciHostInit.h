// gta4l bounded host-local SDHCI initialization.
//
// This header is the single source of the host-init MMIO allowlist and write
// masks used by the probe and by scripts/test-gta4l-sdhci-host-init.py.
// The probe may write only the four standard SDHCI registers listed below. It
// must not write power control, vendor power-control registers, GCC branches,
// RCGs, PLLs or the block reset. See docs/sdhci-host-init.md.

#ifndef GTA4L_SDHCI_HOST_INIT_H
#define GTA4L_SDHCI_HOST_INIT_H

#define GTA4L_SDHCI_HOST_INIT_SDHCI_BASE       0x04744000u
#define GTA4L_SDHCI_HOST_INIT_SDHCI_SIZE       0x00001000u
#define GTA4L_SDHCI_HOST_INIT_GCC_BASE         0x01438000u
#define GTA4L_SDHCI_HOST_INIT_GCC_SIZE         0x00001000u

/* Standard SDHCI registers. */
#define GTA4L_SDHCI_HOST_INIT_REG_PRESENT_STATE       0x24u
#define GTA4L_SDHCI_HOST_INIT_REG_POWER_CONTROL       0x29u
#define GTA4L_SDHCI_HOST_INIT_REG_CLOCK_CONTROL       0x2Cu
#define GTA4L_SDHCI_HOST_INIT_REG_SOFTWARE_RESET      0x2Fu
#define GTA4L_SDHCI_HOST_INIT_REG_INT_ENABLE          0x34u
#define GTA4L_SDHCI_HOST_INIT_REG_SIGNAL_ENABLE       0x38u

/* Qualcomm v5 vendor registers. */
#define GTA4L_SDHCI_HOST_INIT_REG_MCI_VERSION         0x318u
#define GTA4L_SDHCI_HOST_INIT_REG_CORE_GENERICS       0x320u
#define GTA4L_SDHCI_HOST_INIT_REG_CORE_PWRCTL_STATUS  0x240u
#define GTA4L_SDHCI_HOST_INIT_REG_CORE_PWRCTL_MASK    0x244u
#define GTA4L_SDHCI_HOST_INIT_REG_CORE_VENDOR_SPEC    0x20Cu
#define GTA4L_SDHCI_HOST_INIT_REG_CORE_DDR_CONFIG     0x25Cu
#define GTA4L_SDHCI_HOST_INIT_REG_CORE_DLL_STATUS     0x208u

/* SM6115 GCC SDCC1 page at 0x1400000 + 0x38000, page-relative offsets. */
#define GTA4L_SDHCI_HOST_INIT_REG_GCC_SDCC1_BCR       0x00u
#define GTA4L_SDHCI_HOST_INIT_REG_GCC_SDCC1_APPS_CBCR 0x04u
#define GTA4L_SDHCI_HOST_INIT_REG_GCC_SDCC1_AHB_CBCR  0x08u
#define GTA4L_SDHCI_HOST_INIT_REG_GCC_SDCC1_ICE_CBCR  0x0Cu
#define GTA4L_SDHCI_HOST_INIT_REG_GCC_SDCC1_APPS_CMD  0x28u
#define GTA4L_SDHCI_HOST_INIT_REG_GCC_SDCC1_APPS_CFG  0x2Cu
#define GTA4L_SDHCI_HOST_INIT_REG_GCC_SDCC1_APPS_M    0x30u
#define GTA4L_SDHCI_HOST_INIT_REG_GCC_SDCC1_APPS_N    0x34u
#define GTA4L_SDHCI_HOST_INIT_REG_GCC_SDCC1_APPS_D    0x38u

/* Read widths. The four writable standard registers are included. */
#define GTA4L_SDHCI_HOST_INIT_WIDTH_PRESENT_STATE       32u
#define GTA4L_SDHCI_HOST_INIT_WIDTH_POWER_CONTROL       8u
#define GTA4L_SDHCI_HOST_INIT_WIDTH_CLOCK_CONTROL       16u
#define GTA4L_SDHCI_HOST_INIT_WIDTH_SOFTWARE_RESET      8u
#define GTA4L_SDHCI_HOST_INIT_WIDTH_INT_ENABLE          32u
#define GTA4L_SDHCI_HOST_INIT_WIDTH_SIGNAL_ENABLE       32u
#define GTA4L_SDHCI_HOST_INIT_WIDTH_MCI_VERSION         32u
#define GTA4L_SDHCI_HOST_INIT_WIDTH_CORE_GENERICS       32u
#define GTA4L_SDHCI_HOST_INIT_WIDTH_CORE_PWRCTL_STATUS  32u
#define GTA4L_SDHCI_HOST_INIT_WIDTH_CORE_PWRCTL_MASK    32u
#define GTA4L_SDHCI_HOST_INIT_WIDTH_CORE_VENDOR_SPEC    32u
#define GTA4L_SDHCI_HOST_INIT_WIDTH_CORE_DDR_CONFIG     32u
#define GTA4L_SDHCI_HOST_INIT_WIDTH_CORE_DLL_STATUS     32u
#define GTA4L_SDHCI_HOST_INIT_WIDTH_GCC_SDCC1_BCR       32u
#define GTA4L_SDHCI_HOST_INIT_WIDTH_GCC_SDCC1_APPS_CBCR 32u
#define GTA4L_SDHCI_HOST_INIT_WIDTH_GCC_SDCC1_AHB_CBCR  32u
#define GTA4L_SDHCI_HOST_INIT_WIDTH_GCC_SDCC1_ICE_CBCR  32u
#define GTA4L_SDHCI_HOST_INIT_WIDTH_GCC_SDCC1_APPS_CMD  32u
#define GTA4L_SDHCI_HOST_INIT_WIDTH_GCC_SDCC1_APPS_CFG  32u
#define GTA4L_SDHCI_HOST_INIT_WIDTH_GCC_SDCC1_APPS_M    32u
#define GTA4L_SDHCI_HOST_INIT_WIDTH_GCC_SDCC1_APPS_N    32u
#define GTA4L_SDHCI_HOST_INIT_WIDTH_GCC_SDCC1_APPS_D    32u

/* Standard SDHCI field values. */
#define GTA4L_SDHCI_HOST_INIT_POWER_BUS_POWER       0x01u
#define GTA4L_SDHCI_HOST_INIT_CLOCK_INT_EN          0x0001u
#define GTA4L_SDHCI_HOST_INIT_CLOCK_INT_STABLE      0x0002u
#define GTA4L_SDHCI_HOST_INIT_CLOCK_CARD_EN         0x0004u
#define GTA4L_SDHCI_HOST_INIT_SOFTWARE_RESET_ALL    0x01u
#define GTA4L_SDHCI_HOST_INIT_PRESENT_CMD_INHIBIT   0x00000001u
#define GTA4L_SDHCI_HOST_INIT_PRESENT_DAT_INHIBIT   0x00000002u

/* GCC branch and RCG fields used only for the preconditions. */
#define GTA4L_SDHCI_HOST_INIT_CBCR_CLK_OFF          (1u << 31)
#define GTA4L_SDHCI_HOST_INIT_CBCR_CLOCK_ENABLE     (1u << 0)
#define GTA4L_SDHCI_HOST_INIT_RCG_CMD_UPDATE        (1u << 0)
#define GTA4L_SDHCI_HOST_INIT_RCG_CMD_ROOT_OFF      (1u << 31)
#define GTA4L_SDHCI_HOST_INIT_RCG_SRC_SEL_MASK      (0x7u << 8)
#define GTA4L_SDHCI_HOST_INIT_RCG_SRC_SEL_GPLL6     (4u << 8)
#define GTA4L_SDHCI_HOST_INIT_RCG_SRC_DIV_MASK      0xFFu
#define GTA4L_SDHCI_HOST_INIT_RCG_SRC_DIV_EXPECTED  1u
#define GTA4L_SDHCI_HOST_INIT_RCG_MODE_MASK         (0x3u << 12)

/* Ten milliseconds at the documented 19.2 MHz SM6115 counter, plus a hard
 * iteration cap so a stuck counter cannot create an unbounded loop. */
#define GTA4L_SDHCI_HOST_INIT_TIMEOUT_TICKS        192000u
#define GTA4L_SDHCI_HOST_INIT_MAX_POLL_ITERATIONS  100000u

#endif /* GTA4L_SDHCI_HOST_INIT_H */
